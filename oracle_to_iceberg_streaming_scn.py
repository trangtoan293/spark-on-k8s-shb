import os
import sys
import argparse
import logging
from typing import Optional, Dict, Any
from datetime import datetime
import json
from urllib.parse import quote_plus
from pyspark.sql import SparkSession, DataFrame
from pyspark.sql.functions import col, max as spark_max, current_timestamp, lit, when, coalesce
from pyspark.sql.types import LongType

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

class OracleToIcebergSCNStreaming:
    """Oracle to Iceberg streaming loader using ORA_ROWSCN for CDC"""
    
    def __init__(self):
        self.spark = None
        self.oracle_config = self._get_oracle_config()
        self.streaming_query = None
        self.scn_column = "ORA_ROWSCN"  # Oracle System Change Number column
        
    def _get_oracle_config(self) -> dict:
        """Get Oracle configuration from environment variables"""
        config = {
            'host': os.getenv('ORACLE_HOST', '192.168.1.58'),
            'port': os.getenv('ORACLE_PORT', '1521'),
            'service': os.getenv('ORACLE_SERVICE', 'DATALAKE'),
            'username': os.getenv('ORACLE_USERNAME', 'lakehouse'),
            'password': os.getenv('ORACLE_PASSWORD', 'l@ke246')
        }
        
        required_fields = ['host', 'service', 'username', 'password']
        missing_fields = [field for field in required_fields if not config[field]]
        
        if missing_fields:
            raise ValueError(f"Missing required environment variables: {missing_fields}")
        
        logger.info(f"Oracle config loaded: {config['host']}:{config['port']}/{config['service']}")
        return config
    
    def create_spark_session(self) -> SparkSession:
        """Create Spark session optimized for CDC operations"""
        try:
            spark = SparkSession.getActiveSession()
            if spark is None:
                logger.info("Creating Spark session optimized for Oracle CDC")
                spark = SparkSession.builder \
                    .appName("oracle-to-iceberg-scn-cdc") \
                    .config("spark.sql.streaming.checkpointLocation.cleaner.enabled", "true") \
                    .config("spark.sql.streaming.minBatchesToRetain", "10") \
                    .config("spark.sql.adaptive.enabled", "true") \
                    .config("spark.sql.adaptive.coalescePartitions.enabled", "true") \
                    .getOrCreate()
                    
                spark.sparkContext.setLogLevel("WARN")
            else:
                logger.info("Reusing existing Spark session")
                
            return spark
        except Exception as e:
            logger.error(f"Failed to create Spark session: {e}")
            raise
    
    def build_oracle_jdbc_url(self) -> str:
        """Build Oracle JDBC URL with proper encoding"""
        encoded_username = quote_plus(self.oracle_config['username'])
        encoded_password = quote_plus(self.oracle_config['password'])
        
        jdbc_url = f"jdbc:oracle:thin:{encoded_username}/{encoded_password}@//{self.oracle_config['host']}:{self.oracle_config['port']}/{self.oracle_config['service']}"
        logger.debug("JDBC URL built successfully")
        return jdbc_url
    
    def get_last_scn_checkpoint(self, checkpoint_location: str, table_name: str) -> Optional[int]:
        """Retrieve last processed SCN from checkpoint"""
        try:
            checkpoint_file = f"{checkpoint_location}/scn_checkpoint/{table_name}.json"
            
            # Read checkpoint from S3/MinIO
            checkpoint_df = self.spark.read.option("multiline", "true").json(checkpoint_file)
            if checkpoint_df.count() > 0:
                last_scn = checkpoint_df.select("last_scn").collect()[0]["last_scn"]
                logger.info(f"Retrieved SCN checkpoint: {last_scn}")
                return int(last_scn)
            else:
                logger.info("No previous SCN checkpoint found, starting from beginning")
                return None
                
        except Exception as e:
            logger.info(f"No SCN checkpoint found or error reading: {e}")
            return None
    
    def save_scn_checkpoint(self, checkpoint_location: str, table_name: str, scn: int):
        """Save current processing SCN to checkpoint"""
        try:
            checkpoint_data = {
                "table_name": table_name,
                "last_scn": scn,
                "updated_at": datetime.now().isoformat(),
                "checkpoint_type": "ora_rowscn"
            }
            
            checkpoint_file = f"{checkpoint_location}/scn_checkpoint/{table_name}.json"
            
            # Create checkpoint DataFrame and save
            checkpoint_df = self.spark.createDataFrame([checkpoint_data])
            checkpoint_df.coalesce(1).write \
                .mode("overwrite") \
                .option("multiline", "true") \
                .json(checkpoint_file)
                
            logger.info(f"SCN checkpoint saved: {scn}")
            
        except Exception as e:
            logger.warning(f"Failed to save SCN checkpoint: {e}")
    
    def read_oracle_incremental_scn(self, table_name: str, last_scn: Optional[int] = None) -> DataFrame:
        """Read Oracle table incrementally using ORA_ROWSCN"""
        logger.info(f"Reading Oracle table with SCN-based CDC: {table_name}")
        
        if not self.spark:
            raise RuntimeError("Spark session not initialized")
        
        jdbc_url = self.build_oracle_jdbc_url()
        
        # Build SCN-based incremental query
        if last_scn:
            # Incremental read: only records with SCN > last checkpoint
            incremental_query = f"""
            (SELECT *, ORA_ROWSCN as CDC_SCN 
             FROM {table_name} 
             WHERE ORA_ROWSCN > {last_scn}
             ORDER BY ORA_ROWSCN) oracle_incremental
            """
            logger.info(f"Incremental SCN query: WHERE ORA_ROWSCN > {last_scn}")
        else:
            # Initial load: all records with SCN
            incremental_query = f"""
            (SELECT *, ORA_ROWSCN as CDC_SCN 
             FROM {table_name} 
             ORDER BY ORA_ROWSCN) oracle_initial
            """
            logger.info("Initial SCN-based full load")
        
        # JDBC options optimized for SCN-based reads
        jdbc_options = {
            "url": jdbc_url,
            "dbtable": incremental_query,
            "driver": "oracle.jdbc.driver.OracleDriver",
            "fetchsize": "5000",  # Larger batch for performance
            "queryTimeout": "600",
            "numPartitions": "4",   # Parallel processing
            "partitionColumn": "CDC_SCN",  # Use SCN for partitioning
            "lowerBound": str(last_scn) if last_scn else "1",
            "upperBound": "999999999999"  # High SCN value
        }
        
        try:
            df = self.spark.read.format("jdbc").options(**jdbc_options).load()
            
            # Add CDC metadata columns
            df_with_metadata = df \
                .withColumn("_cdc_extracted_at", current_timestamp()) \
                .withColumn("_cdc_source_system", lit("oracle")) \
                .withColumn("_cdc_operation", lit("upsert")) \
                .withColumn("_cdc_checkpoint_scn", col("CDC_SCN").cast(LongType()))
            
            record_count = df_with_metadata.count()
            logger.info(f"Read {record_count:,} incremental records using SCN CDC")
            
            return df_with_metadata
            
        except Exception as e:
            logger.error(f"Failed to read Oracle table with SCN CDC: {e}")
            raise
    
    def ensure_iceberg_table_exists(self, iceberg_table: str, source_df: DataFrame):
        """Ensure Iceberg table exists with proper schema for CDC"""
        try:
            # Check if table exists
            self.spark.sql(f"DESCRIBE TABLE {iceberg_table}")
            logger.info(f"Iceberg table '{iceberg_table}' exists")
            
        except Exception:
            logger.info(f"Creating Iceberg table '{iceberg_table}' with CDC metadata")
            
            # Create first record to establish schema
            first_record = source_df.limit(1)
            first_record.write \
                .format("iceberg") \
                .mode("overwrite") \
                .option("write.upsert.enabled", "true") \
                .option("write.merge.mode", "merge-on-read") \
                .option("format-version", "2") \
                .saveAsTable(iceberg_table)
                
            logger.info(f"Iceberg table '{iceberg_table}' created with CDC schema")
    
    def merge_to_iceberg_scn(self, source_df: DataFrame, iceberg_table: str, primary_key: str):
        """Perform MERGE operation using SCN-based logic"""
        logger.info(f"Performing SCN-based MERGE on '{iceberg_table}' with key '{primary_key}'")
        
        try:
            # Create temporary view for MERGE
            temp_view = f"temp_{iceberg_table.replace('.', '_')}_scn_updates"
            source_df.createOrReplaceTempView(temp_view)
            
            # Advanced MERGE SQL with SCN-based conflict resolution
            merge_sql = f"""
            MERGE INTO {iceberg_table} AS target
            USING {temp_view} AS source
            ON target.{primary_key} = source.{primary_key}
            
            WHEN MATCHED AND source._cdc_checkpoint_scn > COALESCE(target._cdc_checkpoint_scn, 0) THEN
                UPDATE SET *
                
            WHEN NOT MATCHED THEN
                INSERT *
            """
            
            logger.info("Executing SCN-based MERGE operation...")
            
            try:
                result = self.spark.sql(merge_sql)
                logger.info("SCN-based MERGE completed successfully")
                
            except Exception as merge_error:
                logger.warning(f"MERGE operation failed, falling back to append: {merge_error}")
                # Fallback: append with deduplication
                source_df.write \
                    .format("iceberg") \
                    .mode("append") \
                    .saveAsTable(iceberg_table)
                
        except Exception as e:
            logger.error(f"SCN-based MERGE operation failed: {e}")
            raise
    
    def process_scn_batch(
        self, 
        oracle_table: str, 
        iceberg_table: str, 
        checkpoint_location: str,
        primary_key: str
    ):
        """Process incremental batch using SCN checkpointing"""
        
        try:
            # Step 1: Get last SCN checkpoint
            last_scn = self.get_last_scn_checkpoint(checkpoint_location, oracle_table)
            
            # Step 2: Read incremental data using SCN
            incremental_df = self.read_oracle_incremental_scn(oracle_table, last_scn)
            
            if incremental_df.count() == 0:
                logger.info("No new data to process (no higher SCN values)")
                return
            
            # Step 3: Ensure Iceberg table exists
            self.ensure_iceberg_table_exists(iceberg_table, incremental_df)
            
            # Step 4: Perform SCN-based MERGE
            self.merge_to_iceberg_scn(incremental_df, iceberg_table, primary_key)
            
            # Step 5: Update SCN checkpoint
            max_scn = incremental_df.agg(
                spark_max(col("_cdc_checkpoint_scn")).alias("max_scn")
            ).collect()[0]["max_scn"]
            
            if max_scn:
                self.save_scn_checkpoint(checkpoint_location, oracle_table, int(max_scn))
                logger.info(f"SCN batch processed successfully. Max SCN: {max_scn}")
            
        except Exception as e:
            logger.error(f"SCN batch processing failed: {e}")
            raise
    
    def start_scn_streaming(
        self,
        oracle_table: str,
        iceberg_table: str,
        primary_key: str = "ID",
        trigger_interval: str = "2 minutes",
        checkpoint_location: str = "s3a://data/checkpoints/oracle-scn-cdc"
    ):
        """Start SCN-based incremental streaming"""
        
        logger.info(f"Starting SCN-based CDC streaming: {oracle_table} -> {iceberg_table}")
        logger.info(f"Primary key: {primary_key}, Trigger interval: {trigger_interval}")
        
        if not self.spark:
            raise RuntimeError("Spark session not initialized")
        
        # Use rate stream as processing trigger
        rate_stream = self.spark \
            .readStream \
            .format("rate") \
            .option("rowsPerSecond", "1") \
            .load()
        
        def process_scn_micro_batch(batch_df, batch_id):
            """Process each SCN-based micro-batch"""
            logger.info(f"Processing SCN-based micro-batch {batch_id}")
            
            try:
                self.process_scn_batch(
                    oracle_table, 
                    iceberg_table, 
                    checkpoint_location,
                    primary_key
                )
                logger.info(f"SCN micro-batch {batch_id} completed successfully")
                
            except Exception as e:
                logger.error(f"SCN micro-batch {batch_id} failed: {e}")
                raise
        
        # Start SCN-based streaming query
        self.streaming_query = rate_stream.writeStream \
            .foreachBatch(process_scn_micro_batch) \
            .trigger(processingTime=trigger_interval) \
            .option("checkpointLocation", f"{checkpoint_location}/streaming") \
            .start()
        
        logger.info("SCN-based CDC streaming started successfully")
        logger.info("Press Ctrl+C to stop streaming")
        
        try:
            self.streaming_query.awaitTermination()
        except KeyboardInterrupt:
            logger.info("Stopping SCN-based CDC streaming...")
            self.stop_streaming()
    
    def stop_streaming(self):
        """Stop the streaming query gracefully"""
        if self.streaming_query and self.streaming_query.isActive:
            logger.info("Stopping SCN-based streaming query...")
            self.streaming_query.stop()
            logger.info("SCN streaming query stopped")
    
    def close(self):
        """Close Spark session and stop streaming"""
        self.stop_streaming()
        if self.spark:
            self.spark.stop()
            logger.info("Spark session closed")

def main():
    """Main function with SCN-based CDC interface"""
    parser = argparse.ArgumentParser(
        description="Oracle to Iceberg CDC streaming using ORA_ROWSCN"
    )
    parser.add_argument("--oracle-table", required=True, 
                       help="Oracle source table name")
    parser.add_argument("--iceberg-table", required=True, 
                       help="Iceberg target table name (e.g., demo.customers)")
    parser.add_argument("--primary-key", default="ID", 
                       help="Primary key column for MERGE operations")
    parser.add_argument("--trigger-interval", default="2 minutes",
                       help="Processing interval (e.g., '2 minutes', '30 seconds')")
    parser.add_argument("--checkpoint-location", 
                       default="s3a://data/checkpoints/oracle-scn-cdc",
                       help="Checkpoint location for SCN state management")
    parser.add_argument("--one-time", action="store_true",
                       help="Run one-time SCN batch instead of continuous streaming")
    
    args = parser.parse_args()
    
    loader = None
    try:
        # Initialize SCN-based CDC loader
        loader = OracleToIcebergSCNStreaming()
        
        # Create Spark session
        loader.spark = loader.create_spark_session()
        
        if args.one_time:
            # One-time SCN-based batch processing
            logger.info("Running one-time SCN-based CDC batch")
            loader.process_scn_batch(
                oracle_table=args.oracle_table,
                iceberg_table=args.iceberg_table,
                checkpoint_location=args.checkpoint_location,
                primary_key=args.primary_key
            )
            logger.info("One-time SCN CDC batch completed!")
        else:
            # Continuous SCN-based streaming
            loader.start_scn_streaming(
                oracle_table=args.oracle_table,
                iceberg_table=args.iceberg_table,
                primary_key=args.primary_key,
                trigger_interval=args.trigger_interval,
                checkpoint_location=args.checkpoint_location
            )
        
        sys.exit(0)
        
    except KeyboardInterrupt:
        logger.info("SCN-based CDC streaming stopped by user")
        sys.exit(0)
    except Exception as e:
        logger.error(f"SCN-based CDC streaming failed: {e}")
        sys.exit(1)
        
    finally:
        if loader:
            loader.close()

if __name__ == "__main__":
    main()